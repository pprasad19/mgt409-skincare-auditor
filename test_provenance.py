"""No search term in this app is a machine translation.

For two days the resolver carried 232 non-English ingredient names that
were generated by a model and never read by a speaker of Korean,
Japanese, Chinese or French. They were the largest unverified surface in
the project. The first answer was disclosure: the page flagged any
product whose actives were found only through a translated term, naming
the ingredient and the language, and this file tested that both
directions worked.

Withdrawn on 26 October 2026, because disclosure was the wrong answer. A
wrong translation does not produce a vague result, it produces a warning
about a conflict the user does not have — and that warning is wrong
whether or not a caveat sits beside it. Everything else in the rule
table can be argued with: a `reasoned` row records the mechanism it
rests on and a reader can judge it. A machine translation has no
reasoning to inspect. It is a string a model produced.

So this file now tests the stronger property. Not "an unverified term
declares itself" but "there are no unverified terms", enforced where it
cannot be undone by accident — if someone loads the alias file again,
these fail.

The capability loss is small and is checked here too: INCI nomenclature
is international and required on the ingredient list by EU, Korean and
Japanese regulation, so a non-English label still resolves. What is gone
is the handling of labels printing only a local name, where the failure
is a missing finding rather than an invented one.

The flagging mechanism itself is deliberately left in the code. If four
speakers ever check the file, loading it again should restore the
warning rather than require it to be rebuilt — so the plumbing is
asserted to still work, driven by a synthetic term rather than a real
one.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))

import yaml  # noqa: E402

from models import InputProduct  # noqa: E402
from rules import Rules  # noqa: E402

R = Rules()
failures: list[str] = []
checks = 0


def check(label: str, got, want) -> None:
    global checks
    checks += 1
    if got != want:
        failures.append(f"{label}\n      got:  {got!r}\n      want: {want!r}")


def check_true(label: str, cond: bool, detail: str = "") -> None:
    global checks
    checks += 1
    if not cond:
        failures.append(f"{label}{': ' + detail if detail else ''}")


def resolve(name: str, *ingredients: str):
    return R.resolve(InputProduct(name=name, listed_ingredients=list(ingredients)))


# --- nothing unverified is loaded -------------------------------------
kinds: dict[str, int] = {}
for _term, _id, kind in R.terms:
    kinds[kind] = kinds.get(kind, 0) + 1

check("every term kind is one a human has checked",
      sorted(kinds), ["alias", "inci", "name"])
check("no translated term is loaded at all",
      [k for k in kinds if k.startswith("intl:")], [])
check_true("and there are still enough terms to work with",
           sum(kinds.values()) > 100, str(sum(kinds.values())))

# The file is still in the repository — withdrawn, not deleted, so the
# work survives for whoever has the speakers. What must not happen is it
# silently becoming live again.
alias_file = Path(__file__).resolve().parent / "data" / "ingredient_aliases.yaml"
check_true("the alias file is kept for a future reviewer", alias_file.is_file())
if alias_file.is_file():
    doc = yaml.safe_load(alias_file.read_text(encoding="utf-8")) or {}
    entries = doc.get("aliases") or {}
    written = sum(len(v) for langs in entries.values() for v in langs.values())
    check_true("and still holds the work that was done",
               written > 200, f"{written} terms")
    # Checking term-by-term that none of them reached the resolver looks
    # like the obvious test and is wrong: nine of the entries are words
    # that are independently English or INCI — avobenzone, niacinamide,
    # squalane, centella asiatica — and they are live for that reason,
    # not because the file was loaded. Their presence proves nothing.
    #
    # The kind column is the real guarantee and it is exact: a term can
    # only enter the table through one of the four sources, the file is
    # the only `intl:*` source, and no live term carries that kind. The
    # non-Latin entries are the ones with no other way in, so they are
    # the ones worth naming.
    non_latin = sorted({t for langs in entries.values()
                        for lang, v in langs.items() if lang != "fr"
                        for t in v if not t.isascii()})
    live = {t for t, _i, _k in R.terms}
    check_true("there are non-Latin entries that could only come from the file",
               len(non_latin) > 100, f"{len(non_latin)} terms")
    check("and none of them is in the resolver",
          sorted(t for t in non_latin if t.lower() in live), [])


# --- the capability that remains --------------------------------------
# This is the case the withdrawal was chosen to preserve, and the reason
# the cost is low: regulation puts INCI on the label.
for label, terms, want in [
    ("Korean label printing INCI", ["정제수", "Niacinamide"], "niacinamide"),
    ("Japanese label printing INCI", ["水", "Retinol"], "retinol"),
    ("French label printing INCI", ["Aqua", "Niacinamide"], "niacinamide"),
    ("Chinese label printing INCI", ["水", "Salicylic Acid"], "salicylic_acid"),
]:
    got = resolve("x", *terms)
    check_true(label, want in got.actives, f"{terms} -> {got.actives}")

# And the case that is now deliberately unsupported. Finding nothing is
# the point: a missing finding is safe, an invented one is not.
for label, terms in [
    ("Korean local names only", ["정제수", "나이아신아마이드"]),
    ("Japanese local names only", ["水", "レチノール"]),
    ("Chinese local names only", ["水", "烟酰胺"]),
]:
    got = resolve("x", *terms)
    check(f"{label} resolves to nothing", got.actives, [])
    check(f"{label} flags nothing either", got.translated_only, {})


# --- an English shelf is untouched ------------------------------------
# The withdrawal must not have cost anything in the ordinary case.
plain = resolve("Plain Serum", "Water", "Niacinamide", "Glycerin")
check_true("an English label still resolves", "niacinamide" in plain.actives,
           str(plain.actives))
check("and is not flagged", plain.translated_only, {})

inci = resolve("INCI Serum", "Aqua", "Retinol", "Tocopherol")
check_true("an INCI label still resolves", "retinol" in inci.actives)

audit = R.audit([
    InputProduct(name="Retinol Serum", listed_ingredients=["Retinol"]),
    InputProduct(name="BHA", listed_ingredients=["Salicylic Acid"]),
], concerns=[])
check_true("and a real conflict is still found", len(audit.findings) >= 1,
           str([f.rule_id for f in audit.findings]))
check("with nothing flagged as translated",
      [p.product.name for p in audit.products if p.translated_only], [])


# --- the mechanism is still there, for whoever has the speakers -------
# Driven by a synthetic term so the plumbing is exercised without any
# unverified data being loaded. If this breaks, reinstating the file
# after a review would silently lose the warning that made it tolerable.
R.terms = R.terms + [("zzsynthetic", "niacinamide", "intl:xx")]
flagged = resolve("Synthetic", "zzsynthetic")
check("the flagging mechanism still works if ever needed",
      flagged.translated_only, {"Niacinamide": "xx"})
check_true("and still finds the active", "niacinamide" in flagged.actives)
R.terms = [t for t in R.terms if t[0] != "zzsynthetic"]


if failures:
    print(f"FAILED {len(failures)} of {checks} checks\n")
    for f in failures:
        print(f"  {f}")
    raise SystemExit(1)

print(f"ok  {checks} checks passed")
print(f"    {sum(kinds.values())} search terms, every one INCI, a product name")
print("    or a reviewed alias; the 232 machine translations are kept in the")
print("    repository and kept out of the resolver")
